"""Regenerate the six golden HDF5 fixtures with the 2.0 writer (P3.1).

Not part of the test suite: it rewrites tracked fixtures, so it is run
deliberately, never on a gate. Steps per the plan:

1. Convert each root source log into a staging path.
2. Verify every dataset the old fixture had survives with identical values, and
   that every attribute survives except `schema_version` and `source_file`.
   Added datasets are reported, not rejected: the 2.1 pressure work added some
   and the old goldens predate it.
3. Replace atomically with os.replace.
4. Print the size and sha256 the manifest needs.

Run from the repo root:
    .venv/bin/python scripts/regenerate_golden_fixtures.py [--apply]

Without --apply it only verifies and reports, so a dry run is the default.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import h5py  # noqa: E402
import numpy as np  # noqa: E402

from helios_parser import write_hdf5  # noqa: E402

# (source log, [target fixtures]) - Cu_0166 feeds two identical goldens.
FIXTURES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Cu_0166.log", ("Cu_0166_stabilized.h5", "outputs/hdf5/Cu_0166_stabilized.h5")),
    ("5Fe+4.9TW+light.log", ("outputs/hdf5/5Fe+4.9TW+light_stabilized.h5",)),
    ("10ns+10Si+60Al+15Si+4.27TW.log", ("outputs/hdf5/10ns+10Si+60Al+15Si+4.27TW_stabilized.h5",)),
    ("50Al+10E+25CH+3.5TW.log", ("50Al+10E+25CH+3.5TW_stabilized.h5",)),
    ("Cu1e17_cyl.log", ("Cu1e17_cyl_stabilized.h5",)),
)

# These legitimately differ: the writer stamps the current version, and the old
# goldens recorded an absolute authoring path rather than the source basename.
ATTRIBUTE_EXEMPT = {"schema_version", "source_file"}

# Datasets that legitimately change when the fixture is regenerated by a newer
# writer.
#   available_fields  gains plasma_pressure_j_cm3 from the 2.1 pressure work
#   source_file       recorded an absolute authoring path, now the basename
#   grid/x            the old goldens stored the log's Radius column as-is, which
#   fields/radius     is an EDGE. The writer now stores zone CENTRES and puts the
#                     edges in grid/coordinate_edge. Verified on Cu_0166: the new
#                     centre[-1] plus half the outer zone width reproduces the old
#                     value to the digit (9.206e-02 + 3.814e-02 = 1.302e-01), and
#                     fields/radius equals grid/dynamic_coordinate_center exactly.
#                     So the goldens were stale, not the writer wrong.
DATASET_EXEMPT = {
    "metadata/available_fields",
    "metadata/source_file",
    "grid/x",
    "fields/radius",
}


def parse_log_edges(log_path: Path, limit: int = 2) -> list[np.ndarray]:
    """Read the Radius column of the first few snapshots straight from the log.

    The column has one row per zone boundary, so a snapshot with `n_zones` zones
    yields `n_zones + 1` values. Parsing it here, rather than trusting the
    converter, is what lets the coordinate exemption below be checked instead of
    asserted.
    """

    lines = log_path.read_text(encoding="utf-8", errors="ignore").splitlines()
    headers = [index for index, line in enumerate(lines) if line.strip().startswith("#    Radius")]
    snapshots: list[np.ndarray] = []
    for header in headers[:limit]:
        radius: list[float] = []
        for line in lines[header + 1 :]:
            parts = line.split()
            if not parts:
                continue
            if not parts[0].isdigit():
                if radius:
                    break
                continue
            if int(parts[0]) == 0 and radius:
                break
            radius.append(float(parts[1]))
        if radius:
            snapshots.append(np.asarray(radius, dtype=np.float64))
    return snapshots


def verify_old_coordinates_against_log(target: Path, log_path: Path) -> list[str]:
    """Prove the OLD fixture stored edges where centres belong.

    The exemption for `grid/x` and `fields/radius` is only honest if the old
    file really is the one that was wrong. Compare the old fixture's edge grid
    with the log's own Radius column: if it matches, the old file stored edges,
    and `fields/radius` holding those same values is the defect being corrected.
    """

    problems: list[str] = []
    edges = parse_log_edges(log_path)
    if not edges:
        return [f"could not parse a Radius column from {log_path.name}"]
    with h5py.File(target, "r") as handle:
        if "grid/dynamic_coordinate_edge" in handle:
            stored = np.asarray(handle["grid/dynamic_coordinate_edge"][: len(edges)], dtype=np.float64)
        elif "grid/x" in handle:
            stored = np.asarray(handle["grid/x"][()], dtype=np.float64)[None, :]
        else:
            return problems
        for index, log_edges in enumerate(edges):
            if index >= stored.shape[0]:
                break
            scale = float(np.max(np.abs(log_edges))) or 1.0
            if not np.allclose(stored[index], log_edges, rtol=0.0, atol=scale * 1e-3):
                # Not a failure of the new writer: this only means the old file
                # did not store raw edges, so the exemption needs re-deriving.
                problems.append(
                    f"{target.name}: old snapshot {index} does not match the log Radius column, "
                    "so the edge-to-centre exemption needs re-checking"
                )
                break
    return problems


def verify_coordinate_contract(path: Path) -> list[str]:
    """The centre/edge contract the exemption above relies on.

    Exempting the coordinate datasets would otherwise be a hole, so assert the
    invariant that makes the change correct: centres are stored where centres
    belong, and a centre plus half its zone width lands on the next edge.
    """

    problems: list[str] = []
    with h5py.File(path, "r") as handle:
        grid = handle.get("grid")
        if grid is None or "dynamic_coordinate_center" not in grid:
            return problems
        centre = np.asarray(grid["dynamic_coordinate_center"][()], dtype=np.float64)
        edge = np.asarray(grid["dynamic_coordinate_edge"][()], dtype=np.float64)
        if centre.shape[0] != edge.shape[0] or edge.shape[1] != centre.shape[1] + 1:
            problems.append(f"coordinate shapes disagree: centre {centre.shape}, edge {edge.shape}")
            return problems
        widths = edge[:, 1:] - edge[:, :-1]
        midpoint = centre + 0.5 * widths
        if not np.allclose(midpoint[:, -1], edge[:, -1], rtol=1e-9, atol=0.0):
            problems.append("centre + half-width does not reach the outer edge")
        if "fields/radius" in handle:
            radius = np.asarray(handle["fields/radius"][()], dtype=np.float64)
            if not np.allclose(radius, centre, rtol=1e-12, atol=0.0, equal_nan=True):
                problems.append("fields/radius is not the stored zone centre")
    return problems


def _datasets(path: Path) -> dict[str, h5py.Dataset]:
    found: dict[str, h5py.Dataset] = {}

    def visit(name: str, obj: object) -> None:
        if isinstance(obj, h5py.Dataset):
            found[name] = obj

    with h5py.File(path, "r") as handle:
        handle.visititems(visit)
        # Copy out so the comparison runs after the file closes.
        return {name: dataset[()] for name, dataset in found.items()}


def _attrs(path: Path) -> dict[str, object]:
    with h5py.File(path, "r") as handle:
        return {key: handle.attrs[key] for key in handle.attrs}


def verify(old: Path, new: Path) -> list[str]:
    """Return a list of problems; empty means the values all survived."""

    problems: list[str] = []
    old_data = _datasets(old)
    new_data = _datasets(new)
    missing = sorted(set(old_data) - set(new_data))
    added = sorted(set(new_data) - set(old_data))
    if missing:
        problems.append(f"{len(missing)} dataset(s) lost, e.g. {missing[:5]}")
    differing: list[str] = []
    for name in sorted(set(old_data) & set(new_data)):
        if name in DATASET_EXEMPT:
            continue
        before, after = old_data[name], new_data[name]
        # h5py returns a numpy *scalar* for a 0-d dataset, which is not an
        # ndarray, so test the dtype rather than the type. equal_nan only
        # applies to float data; string and integer datasets reject it.
        if np.issubdtype(np.asarray(before).dtype, np.floating):
            same = np.array_equal(before, after, equal_nan=True)
        else:
            same = np.array_equal(before, after)
        if not same:
            differing.append(name)
    if differing:
        problems.append(f"{len(differing)} dataset(s) changed value, e.g. {differing[:5]}")
    old_attrs = _attrs(old)
    new_attrs = _attrs(new)
    for key, value in old_attrs.items():
        if key in ATTRIBUTE_EXEMPT:
            continue
        if key not in new_attrs:
            problems.append(f"root attribute {key!r} lost")
        elif str(new_attrs[key]) != str(value):
            problems.append(f"root attribute {key!r}: {value!r} -> {new_attrs[key]!r}")
    if added:
        print(f"    added {len(added)} dataset(s): {added[:8]}")
    return problems


def digest(path: Path) -> tuple[int, str]:
    sha = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            sha.update(block)
    return path.stat().st_size, sha.hexdigest()


def main(argv: list[str]) -> int:
    apply = "--apply" in argv
    failures = 0
    for source_name, targets in FIXTURES:
        source = ROOT / source_name
        if not source.is_file():
            print(f"SKIP {source_name}: source missing")
            failures += 1
            continue
        print(f"=== {source_name} -> {', '.join(targets)}")
        staging_dir = Path(tempfile.mkdtemp(prefix="helios-golden-"))
        staged = staging_dir / "staged.h5"
        write_hdf5(source, staged, overwrite=True)
        for target_name in targets:
            target = ROOT / target_name
            if not target.is_file():
                print(f"  {target_name}: target missing, would create")
            else:
                problems = (
                    verify(target, staged)
                    + verify_old_coordinates_against_log(target, source)
                    + verify_coordinate_contract(staged)
                )
                if problems:
                    failures += 1
                    print(f"  {target_name}: FAILED verification")
                    for problem in problems:
                        print(f"    - {problem}")
                    continue
                print(f"  {target_name}: verified")
            size, sha = digest(staged)
            print(f"    size_bytes={size} sha256={sha}")
            if apply:
                # Copy, never move: one staging file feeds several targets.
                # Write beside the target then rename, so a crash mid-copy
                # cannot leave a half-written fixture behind.
                incoming = target.with_suffix(target.suffix + ".incoming")
                shutil.copyfile(staged, incoming)
                os.replace(incoming, target)
                print(f"    replaced {target_name}")
    if failures:
        print(f"\n{failures} problem(s); nothing replaced" if not apply else f"\n{failures} problem(s)")
        return 1
    if not apply:
        print("\nDry run clean. Re-run with --apply to replace.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))